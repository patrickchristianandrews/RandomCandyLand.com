"""Convert original two-pose chibi sprite sheet to 40x40 indexed flash art.
Artists' original generated pixel-art look is preserved, transparent ink=0.
The palette is kept in source order, not sorted by color or histogram.
"""
from pathlib import Path
import base64,hashlib,zlib
import sys

PALETTE_HEX="0000FFDFFF7EFE3CE67DDDBBB5B9F458AC58BB5572F161EE50AA2086000E00000000FFDEFF1DD69CEDBBF4D8BD39E417A3F6AB146AF059AC506B1845000A00000000FFDFFF5CFDD4DD968E18DC50B32E8B105B0F69E960892845000800E000000000FFBEFEDAD679F551F4B0DCD1A4F8DC0FABD2AAEE6A8D51294827000E00000000FF92FF10D718FDF3C5D7F4B7C492C38F8C158B2F7A6D710B30A7000500000000FFB3FF50FED1FDF3EE54AE59D493C36C83907A4C70C930870120000700000000EFF6DFEDE6B5BEEE866FC4D9AB77640F528C690E414A29071825000800000000EFD5D7CCE6F5ED99B74AAE30762EC498C3B963EE720F31883007000700000000FF9DF71CF65CF57ACE5D9DFDF4B8BCB9C37583F66A5160ED3089000A00000000FFBEF71DF5DBCEDECD7C9DDDDC7ED473C3548395723068CD2868000D00000000FFDEFEDAD6BBF5D8F4F8C5188D18BC159AF16B1159CC48C92046000900000000FFDEFEDBE6DBF5D8F517BD38C436BB74839382D1722F496B3047000B00000000FF3DFE5BE67BFDFAFD39C579E477CB338B937A2F68EC28870140000600000000FF1CFE7BFD99EDFAECF8A579E3F6B3F5B2D28AB1628F594B4029000A00000000FFFFFF9DFF1CFE5AEEDDBE1AE4D8A477A3749AB2624F58EC2867000800000000FFDFFF3CF77EE73EF65BC5FBCCD9C3D683946A2F68CD20660180000A0000"
EXPECTED_BLOB_SHA256="2944032f6ebe7a3b3f378f0ace36faddc3ae484380acc6ad5a180243065f9447"
W=40
FRAMES=16
PAYLOAD=Path(__file__).with_name("animal_art_payload.b64")

def encode_frame(pixels):
    """Nibble PackBits: run/control or packed literal/control, optimum by DP."""
    n=len(pixels)
    dp=[10**9]*(n+1);op=[None]*n;dp[n]=0
    for i in range(n-1,-1,-1):
        run=1
        while run<128 and i+run<n and pixels[i+run]==pixels[i]:
            run+=1
        for q in range(2,run+1):
            cost=2+dp[i+q]
            if cost<dp[i]:dp[i]=cost;op[i]=(True,q)
        for q in range(1,min(128,n-i)+1):
            cost=1+(q+1)//2+dp[i+q]
            if cost<dp[i]:dp[i]=cost;op[i]=(False,q)
    result=bytearray();i=0
    while i<n:
        rep,q=op[i]
        if rep:
            result.extend([128+q-1,pixels[i]])
        else:
            result.append(q-1)
            for j in range(i,i+q,2):
                result.append((pixels[j]<<4)|(pixels[j+1] if j+1<i+q else 0))
        i+=q
    assert len(result)==dp[0]
    # Independent decoder: no mismatched nibble order or truncated last run.
    recovered=[];j=0
    while j<len(result):
        head=result[j];j+=1;k=(head&127)+1
        if head&128:
            ink=result[j];j+=1;recovered.extend([ink]*k)
        else:
            for b in result[j:j+(k+1)//2]:
                recovered.extend([b>>4,b&15])
            recovered=recovered[:n]
            j+=(k+1)//2
    assert recovered==pixels
    return result

def make(root):
    b64=PAYLOAD.read_text(encoding="ascii").strip()
    packed=base64.b64decode(b64,validate=True)
    raw=zlib.decompress(packed)
    if hashlib.sha256(raw).hexdigest()!=EXPECTED_BLOB_SHA256:
        raise RuntimeError("Pastel generated chibi asset corrupted or incomplete")
    # First 16*15*2 bytes are an unordered export of colors (discard them).
    # Pinned PALETTE_HEX preserves source palette index order and duplicates.
    pixel_data=raw[480:]
    if len(pixel_data)!=FRAMES*W*W//2:
        raise RuntimeError("Unexpected pixel payload")
    palettes=[int(PALETTE_HEX[k:k+4],16) for k in range(0,len(PALETTE_HEX),4)]
    if len(palettes)!=FRAMES*16:raise RuntimeError("Bad sprite palette")
    offsets=[];blob=bytearray()
    for frame in range(FRAMES):
        offsets.append(len(blob))
        frame_bytes=pixel_data[frame*W*W//2:(frame+1)*W*W//2]
        pixels=[]
        for b in frame_bytes:
            pixels.extend([b>>4,b&15])
        assert len(pixels)==W*W
        blob.extend(encode_frame(pixels))
    if len(blob)>9300:
        raise RuntimeError("Pixel-art PackBits would overflow scarce application flash")
    lines=[
      "/* AUTOGENERATED Pastel animal art: 16x40x40, PackBits nibble format. */",
      "#ifndef PASTEL_SPRITES_H",
      "#define PASTEL_SPRITES_H",
      "#define PASTEL_SPRITE_W 40u",
      "static const unsigned short pastel_sprite_pal[16][16]={",
    ]
    for f in range(FRAMES):
        lines.append(" {"+",".join(f"0x{x:04x}" for x in palettes[f*16:(f+1)*16])+"},")
    lines.extend(["};",
        "static const unsigned int pastel_sprite_ofs[16]={"+",".join(str(x)+"u" for x in offsets)+"};",
        "static const unsigned char pastel_sprite_bits[] = {"])
    for i in range(0,len(blob),32):
        lines.append(" "+",".join("0x%02x"%x for x in blob[i:i+32])+",")
    lines.extend(["};","#endif /* PASTEL_SPRITES_H */",""])
    path=Path(root)/"firmware/src/pastel_sprites.h"
    path.write_text("\n".join(lines),encoding="ascii")
    print(f"Pixel-art frames built: 8 animals x 2 dance poses, 40x40, {len(blob)} B PackBits (was {len(pixel_data)})")

if __name__=="__main__":
    if len(sys.argv)!=2: raise SystemExit("Usage: generate_animal_sprites.py UPSTREAM_ROOT")
    make(sys.argv[1])
