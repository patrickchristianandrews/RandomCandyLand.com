// Every published HTML file must carry exactly one copy of the requested
// GTM-TQRDB5KL snippet, including pages generated by build-standalone.mjs.
const analyticsId = 'GTM-TQRDB5KL';
function verifyAnalytics(dir) {
  if (!fs.existsSync(dir)) return;
  for (const entry of fs.readdirSync(dir, {withFileTypes:true})) {
    const full = dir + '/' + entry.name;
    if (entry.isDirectory()) {verifyAnalytics(full);continue;}
    if (!entry.isFile() || !entry.name.endsWith('.html')) continue;
    const markup = fs.readFileSync(full,'utf8');
    const ids = markup.match(/GTM-TQRDB5KL/g) || [];
    const body = markup.match(/<body\b[^>]*>/i);
    const noscript = '<noscript><iframe src="https://www.googletagmanager.com/ns.html?id=' + analyticsId + '"';
    if (ids.length !== 2 ||
        !markup.includes("w[l].push({'gtm.start':") ||
        !markup.includes("event:'gtm.js'") ||
        !markup.includes("'https://www.googletagmanager.com/gtm.js?id='+i+dl") ||
        !markup.includes("})(window,document,'script','dataLayer','GTM-TQRDB5KL');") ||
        !body || !markup.slice(body.index + body[0].length,body.index + body[0].length + 200).includes(noscript) ||
        markup.includes("gtag('js', new Date());") ||
        markup.includes('GTM-TQ56MKVH')) {
      console.error('Broken, missing, duplicated or outdated GTM installation:',full);
      failures++;
    }
  }
}
