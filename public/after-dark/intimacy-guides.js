const normalize=s=>String(s||'').toLowerCase().replace(/[^a-z0-9\s-]/g,' ').replace(/\s+/g,' ').trim();
const categories=['All guides',...new Set(guides.map(g=>g.category))];
let category='All guides',search='',selectedId='';
function find(q){
 const query=normalize(q);
 if(!query)return null;
 const common=new Set(['how','why','what','where','when','can','could','does','do','is','are','to','a','an','the','my','your','you','for','in','and','or','of','with','have','get','help','learn','me','about','work','works','guide','steps','tips','type','types','orgasm','orgasms','orgasmic']);
 const root=w=>w.length>3&&w.endsWith('s')&&!w.endsWith('ss')?w.slice(0,-1):w;
 const tokens=s=>normalize(s).replace(/-/g,' ').split(' ').filter(Boolean).map(root);
 const words=[...new Set(tokens(query).filter(x=>x.length>=3&&!common.has(x)))];
 if(!words.length)return guides.find(g=>g.id==='orgasm-difficulty')||null;
 const ranked=guides.map(g=>{
  const title=new Set(tokens(g.title)),keyword=new Set(tokens(g.keywords)),id=new Set(tokens(g.id));
  const description=normalize(g.subtitle+' '+g.facts);
  let score=0,exactCount=0;
  for(const w of words){
   if(id.has(w)){score+=12;exactCount++;}
   else if(title.has(w)){score+=9;exactCount++;}
   else if(keyword.has(w)){score+=6;exactCount++;}
   else if(description.includes(w)){score+=0.5;}
  }
  if(query.includes(g.id.replaceAll('-',' ')))score+=8;
  return {g,score,exactCount};
 }).sort((a,b)=>b.score-a.score||b.exactCount-a.exactCount);
 return ranked[0].score>=5&&ranked[0].exactCount>0?ranked[0].g:null;
}
function paint(){
 const grid=$('howto-guide-grid'),count=$('howto-guide-count');
 if(!grid)return;grid.replaceChildren();
 const match=guides.filter(g=>(category==='All guides'||g.category===category)&&
  normalize([g.title,g.subtitle,g.keywords,g.facts,g.category].join(' ')).includes(normalize(search)));
 if(count)count.textContent=match.length+' of '+guides.length+' guides';
 for(const g of match){
  const card=make('article',undefined,'howto-guide-card');
  card.append(make('span',g.category,'howto-guide-category'));
  card.append(make('div',g.icon,'howto-guide-illustration'));
  card.append(make('h3',g.title));
  card.append(make('p',g.subtitle));
  const btn=make('button','Read guide →','btn alt');
  btn.type='button';btn.onclick=()=>open(g.id);
  card.append(btn);grid.append(card);
 }
 if(!match.length)grid.append(make('p','No orgasm guides match those keywords. Try “nipple”, “clitoral”, “vaginal”, “anal”, “testicular” or “multiple”.','howto-empty'));
}
function open(id){
 const g=guides.find(g=>g.id===id);if(!g)return;
 selectedId=g.id;
 const out=$('howto-guide-detail');if(!out)return;
 out.replaceChildren();
 out.append(make('span',g.category,'eyebrow'),make('h2',g.icon+' '+g.title),make('p',g.subtitle,'howto-guide-lead'));
 const box=make('div',undefined,'howto-guide-insight');box.append(make('h3','Understand the experience'),make('p',g.facts));out.append(box);
 const steps=make('section',undefined,'howto-guide-steps');
 steps.append(make('h3','A practical way to get started'));
 const ol=make('ol');g.steps.forEach(s=>ol.append(make('li',s)));steps.append(ol);out.append(steps);
 const myth=make('div',undefined,'howto-guide-callout');myth.append(make('h3','What not to assume'),make('p',g.myth));out.append(myth);
 const care=make('div',undefined,'howto-guide-callout howto-guide-care');care.append(make('h3','Comfort & safety'),make('p',g.safety));out.append(care);
 const refs=make('div',undefined,'howto-guide-sources');refs.append(make('h3','Sexual-health sources & further reading'));
 for(const key of g.sources){const s=sources[key];if(!s)continue;const a=make('a',s.label+' ↗');a.href=s.url;a.rel='noopener noreferrer';a.target='_blank';refs.append(a)}out.append(refs);
 const actions=make('div',undefined,'result-actions');
 const back=make('button','← All guides','btn alt');back.onclick=()=>{selectedId='';out.hidden=true;document.getElementById('howto-filters')?.scrollIntoView({behavior:'smooth',block:'start'})};
 const ask=make('button','💬 Ask Atlas about this','btn alt');ask.onclick=()=>{document.querySelector('[data-tab=chat]')?.click();const inp=$('chatText');if(inp){inp.value='What is a practical, safe starting approach for '+g.title+'?';inp.focus();}};
 const browse=make('button','📚 Browse the Curiosity Atlas','btn alt');browse.onclick=()=>document.querySelector('[data-tab=atlas]')?.click();
 actions.append(back,ask,browse);out.append(actions);
 out.hidden=false;out.scrollIntoView({behavior:'smooth',block:'start'});
}
function init(){
 const filter=$('howto-category'),query=$('howto-search');
 if(!filter||!query)return;
 filter.replaceChildren();
 categories.forEach(name=>{const opt=make('option',name);opt.value=name;filter.append(opt)});
 filter.value=category;filter.addEventListener('change',()=>{category=filter.value;paint()});
 query.addEventListener('input',()=>{search=query.value;paint()});
 document.querySelectorAll('[data-guide-open]').forEach(button=>{
  button.addEventListener('click',()=>{
   document.querySelector('[data-tab=howto]')?.click();
   open(button.dataset.guideOpen);
  });
 });
 const hash=window.location.hash;
 if(hash.startsWith('#howto:')){
  const id=hash.slice('#howto:'.length);
  document.querySelector('[data-tab=howto]')?.click();open(id);
 }
 paint();
}
function answer(question){
 const q=normalize(question);
 // These guides answer orgasm questions only. Do not hijack unrelated Atlas interests.
 if(!/\b(orgasm[a-z]*|climax|coregasm)\b/.test(q))return null;
 if(!/\b(how|why|what|can|could|does|do|is|are|guide|tips|steps|technique|learn|teach|explain|help)\b/.test(q))return null;
 const g=find(question);if(!g)return null;
 return g.title+'\n\n'+g.facts+'\n\n'+g.steps.slice(0,3).map((s,i)=>(i+1)+'. '+s).join('\n')+'\n\n'+g.myth+'\n\nOpen After Dark → Orgasm Guides for the full practical approach, anatomy, safety notes and sources.';
}
window.AfterDarkIntimacyGuides=Object.freeze({guides,open,find,answer});
init();
